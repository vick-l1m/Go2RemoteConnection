/*
robot_viewer.js

Live 3D Go2 robot viewer, shared across go2_movement_controller.html,
go2_joystick.html, and RL_sim_to_real.html. ES module (relies on the
importmap declared in each page) -- distinct from shared.js, which stays a
plain script since other pages depend on its window.Go2Shared global.

Loads the vendored URDF+meshes (app/static/robot_model/, generated by
tools/gen_robot_model_assets.py) with urdf-loader/three.js, then drives the
model's joint angles and base pose from the /ws/robot_pose feed (see
app/api/robot_model_routes.py + app/ros_bridge.py). The model is driven by
literal joint angles off the robot's LowState/SportModeState, so walking,
turning, sitting/standing, and any custom RL action are all reflected
automatically -- there is no per-action wiring here.

Version 1.0
Author: Victor Lim
*/

import * as THREE from "three";
import { OrbitControls } from "three/addons/controls/OrbitControls.js";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import URDFLoader from "urdf-loader";

const URDF_URL = "/app/static/robot_model/go2.urdf";
const RECONNECT_DELAY_MS = 2000;
const KEEPALIVE_MS = 10000;

function authWsSuffix() {
  const token = encodeURIComponent(window.Go2Shared?.state?.AUTH_TOKEN || "");
  return (window.Go2Shared?.state?.AUTH_ENABLED && token) ? `?token=${token}` : "";
}

export function mountGo2Viewer(containerId) {
  const container = document.getElementById(containerId);
  if (!container) {
    console.warn(`mountGo2Viewer: missing container #${containerId}`);
    return null;
  }
  if (container.dataset.go2ViewerMounted === "1") {
    return null; // already mounted (e.g. a page re-running its bootstrap)
  }
  container.dataset.go2ViewerMounted = "1";

  const width = container.clientWidth || 320;
  const height = container.clientHeight || 260;

  const scene = new THREE.Scene();
  scene.background = new THREE.Color(0xe9edf2);

  const camera = new THREE.PerspectiveCamera(45, width / height, 0.05, 20);
  camera.position.set(0.9, 0.7, 0.9);

  const renderer = new THREE.WebGLRenderer({ antialias: true });
  renderer.setPixelRatio(window.devicePixelRatio || 1);
  renderer.setSize(width, height);
  container.appendChild(renderer.domElement);

  const hemiLight = new THREE.HemisphereLight(0xffffff, 0x555555, 1.3);
  scene.add(hemiLight);
  const dirLight = new THREE.DirectionalLight(0xffffff, 0.9);
  dirLight.position.set(1, 2, 1);
  scene.add(dirLight);

  const grid = new THREE.GridHelper(2, 20, 0xbfc6cf, 0xdde2e8);
  scene.add(grid);

  const controls = new OrbitControls(camera, renderer.domElement);
  controls.target.set(0, 0.15, 0);
  controls.enablePan = false;
  controls.minDistance = 0.4;
  controls.maxDistance = 3;
  controls.update();

  // The URDF/telemetry frame is ROS/URDF convention (Z-up); three.js's default
  // camera/controls assume Y-up. Rather than transform every incoming pose
  // sample, wrap the robot in a group that carries the one-time display
  // rotation, and drive the robot object itself directly in its native Z-up
  // frame -- position/quaternion from telemetry apply unmodified.
  const robotRoot = new THREE.Group();
  robotRoot.rotation.x = -Math.PI / 2;
  scene.add(robotRoot);

  let robot = null;
  const gltfLoader = new GLTFLoader();

  const urdfLoader = new URDFLoader();
  urdfLoader.loadMeshCb = (path, manager, material, done) => {
    gltfLoader.load(
      path,
      (gltf) => {
        const obj = gltf.scene;
        if (material) {
          obj.traverse((c) => { if (c.isMesh) c.material = material; });
        }
        done(obj);
      },
      undefined,
      (err) => done(null, err),
    );
  };

  urdfLoader.load(
    URDF_URL,
    (result) => {
      robot = result;
      robotRoot.add(robot);
    },
    undefined,
    (err) => console.error("mountGo2Viewer: failed to load URDF", err),
  );

  // ---------------- Render loop ----------------
  let stopped = false;
  function animate() {
    if (stopped) return;
    requestAnimationFrame(animate);
    controls.update();
    renderer.render(scene, camera);
  }
  animate();

  // Keep the canvas correctly sized if the container's layout changes.
  const resizeObserver = new ResizeObserver(() => {
    const w = container.clientWidth || width;
    const h = container.clientHeight || height;
    camera.aspect = w / h;
    camera.updateProjectionMatrix();
    renderer.setSize(w, h);
  });
  resizeObserver.observe(container);

  // ---------------- Pose WebSocket ----------------
  let ws = null;
  let keepalive = null;
  let reconnectTimer = null;

  function applyPose(msg) {
    if (!robot) return;
    if (msg.joints) {
      for (const [name, angle] of Object.entries(msg.joints)) {
        const joint = robot.joints[name];
        if (joint) joint.setJointValue(angle);
      }
    }
    if (msg.base) {
      const [x, y, z] = msg.base.position;
      const [qx, qy, qz, qw] = msg.base.quaternion;
      robot.position.set(x, y, z);
      robot.quaternion.set(qx, qy, qz, qw);
    }
  }

  function connect() {
    if (stopped) return;
    const base = window.Go2Shared?.apiWsBase?.();
    if (!base) {
      reconnectTimer = setTimeout(connect, RECONNECT_DELAY_MS);
      return;
    }

    ws = new WebSocket(`${base}/ws/robot_pose${authWsSuffix()}`);

    ws.onopen = () => {
      keepalive = setInterval(() => {
        if (ws && ws.readyState === WebSocket.OPEN) {
          try { ws.send("ping"); } catch (_) {}
        }
      }, KEEPALIVE_MS);
    };

    ws.onmessage = (ev) => {
      if (typeof ev.data !== "string") return;
      try {
        applyPose(JSON.parse(ev.data));
      } catch (_) {}
    };

    ws.onclose = () => {
      if (keepalive) { clearInterval(keepalive); keepalive = null; }
      ws = null;
      if (!stopped) reconnectTimer = setTimeout(connect, RECONNECT_DELAY_MS);
    };

    ws.onerror = () => {
      try { ws?.close(); } catch (_) {}
    };
  }
  connect();

  return {
    destroy() {
      stopped = true;
      if (reconnectTimer) clearTimeout(reconnectTimer);
      if (keepalive) clearInterval(keepalive);
      try { ws?.close(); } catch (_) {}
      resizeObserver.disconnect();
      renderer.dispose();
      container.dataset.go2ViewerMounted = "0";
    },
  };
}
